"""E10 --- LaTeX macros for the numbers quoted in the paper's main text.

Reads docs/tables/e10-summary.md (written by scripts/e10_analyze.py) and writes
fact_numbers.tex with one macro per quoted quantity, so the prose never carries
a hand-typed number from the pod campaign.

    python scripts/e10_numbers.py --md docs/tables/e10-summary.md --out <dir>/fact_numbers.tex
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def parse_q3(md: str):
    rows = {}
    sec = md.split("## Q3")[1].split("## W3")[0]
    for line in sec.splitlines():
        if not line.startswith("| ") or line.startswith("| drafter"):
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        if len(c) < 10:
            continue
        drafter, bench, K, tree = c[0], c[1], int(c[2]), c[3]
        rows[(drafter, bench, K, tree)] = dict(acc=float(c[4]), ms=float(c[5]), sp=float(c[6]), step=float(c[7]),
                                               delta=c[8], share=c[9])
    return rows


def parse_w3(md: str):
    rows, inter = {}, {}
    if "## W3" not in md:
        return rows, inter
    sec = md.split("## W3")[1].split("## W2")[0]
    part = sec.split("### interaction")
    for line in part[0].splitlines():
        if not line.startswith("| ") or line.startswith("| bench"):
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        if len(c) < 10:
            continue
        rows[(c[0], int(c[1]), c[2])] = dict(acc_st=float(c[3]), acc_dy=float(c[4]), ms_st=float(c[5]), ms_dy=float(c[6]),
                                            sp_st=float(c[7]), sp_dy=float(c[8]), G=c[9])
    if len(part) > 1:
        for line in part[1].splitlines():
            if not line.startswith("| ") or line.startswith("| bench"):
                continue
            c = [x.strip() for x in line.strip("|").split("|")]
            if len(c) < 6:
                continue
            inter[(c[0], int(c[1]), c[2])] = dict(iabs=c[3], irel=c[4], dacc=c[5])
    return rows, inter


def share_tex(s: str) -> str:
    # "82% [79, 84]" -> "82\% [79, 84]"
    return s.replace("%", r"\%")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default="docs/tables/e10-summary.md")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    md = Path(a.md).read_text(encoding="utf-8")
    q3 = parse_q3(md)
    w3, inter = parse_w3(md)
    L = ["% generated by scripts/e10_numbers.py from docs/tables/e10-summary.md -- do not edit"]

    def m(name, val):
        L.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    def g(drafter, bench, K, tree):
        return q3.get((drafter, bench, K, tree))

    def share_int(txt):
        try:
            return int(txt.split("%")[0])
        except ValueError:  # "--" when the dynamic reference cell is missing
            return None

    # scaled drafter keeps the original names (qSameMTFourShare ...); the transfer drafters get a prefix
    # (qBaseSameMTFourShare, qEagleSameMTFourShare ...)
    for drafter, dtag in (("scaled", ""), ("base", "Base"), ("eagle", "Eagle")):
        for bench, tag in (("mtbench", "MT"), ("humaneval", "HE")):
            for K in (4, 8):
                for tree, ttag in (("optsame", "Same"), ("optfree", "Free"), ("dyn", "Dyn"), ("static", "Static")):
                    r = g(drafter, bench, K, tree)
                    if r:
                        stem = f"q{dtag}{ttag}{tag}{'Four' if K == 4 else 'Eight'}"
                        m(f"{stem}Share", share_tex(r["share"]))
                        m(f"{stem}Sp", f"{r['sp']:.2f}")
                        m(f"{stem}Acc", f"{r['acc']:.2f}")
                        m(f"{stem}Ms", f"{r['ms']:.2f}")
        for tree, ttag in (("optsame", "Same"), ("optfree", "Free")):
            shares = [share_int(q3[k]["share"]) for k in q3 if k[0] == drafter and k[3] == tree]
            shares = [x for x in shares if x is not None]
            if shares:
                rng = f"{min(shares)}--{max(shares)}" if min(shares) != max(shares) else f"{min(shares)}"
                m(f"q{dtag}{ttag}ShareRange", f"{rng}\%")
    # W3 headline: G per checkpoint and the interaction on both scales, seeds separately
    for bench, tag in (("mtbench", "MT"), ("humaneval", "HE")):
        for K in (4, 8):
            for ck, ctag in (("sw-s1", "SwOne"), ("sw-s2", "SwTwo"), ("det-s1", "DetOne"), ("det-s2", "DetTwo")):
                r = w3.get((bench, K, ck))
                if r:
                    kk = "Four" if K == 4 else "Eight"
                    m(f"w{ctag}{tag}{kk}G", r["G"].split(" [")[0])
                    m(f"w{ctag}{tag}{kk}SpSt", f"{r['sp_st']:.2f}")
                    m(f"w{ctag}{tag}{kk}SpDy", f"{r['sp_dy']:.2f}")
            for seed, stag in (("s1", "One"), ("s2", "Two")):
                r = inter.get((bench, K, seed))
                if r:
                    kk = "Four" if K == 4 else "Eight"
                    m(f"wI{tag}{kk}{stag}Abs", r["iabs"].replace("[", "$[").replace("]", "]$") if False else r["iabs"])
                    m(f"wI{tag}{kk}{stag}Rel", r["irel"])
    # W3 summaries over the (bench, K, seed) cells: sw minus det contrasts
    if inter:
        def pt(x):
            return float(x.split(" [")[0].replace("+", ""))

        def ci(x):
            lo, hi = x.split("[")[1].rstrip("]").split(",")
            return float(lo), float(hi)
        dacc = [pt(v["dacc"]) for v in inter.values()]
        irel = [pt(v["irel"]) for v in inter.values()]
        iabs = [pt(v["iabs"]) for v in inter.values()]
        words = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}
        n_abs_excl = sum(1 for v in inter.values() if ci(v["iabs"])[0] > 0)
        m("wCells", str(len(inter)))
        m("wCellsWord", words.get(len(inter), str(len(inter))))
        m("wDaccRange", f"{min(dacc):.2f}--{max(dacc):.2f}")
        m("wDaccExcl", str(sum(1 for v in inter.values() if ci(v["dacc"])[0] > 0)))
        m("wIrelRange", f"{min(irel):.0f}--{max(irel):.0f}\%")
        m("wIrelExcl", str(sum(1 for v in inter.values() if ci(v["irel"])[0] > 0)))
        m("wIabsPos", str(sum(1 for x in iabs if x > 0)))
        m("wIabsExcl", str(n_abs_excl))
        m("wIabsExclWord", words.get(n_abs_excl, str(n_abs_excl)))
        m("wIabsRange", f"{min(iabs):.2f}--{max(iabs):.2f}")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"[E10] wrote {a.out} ({len(L) - 1} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
