"""E8 phase A --- locate the sampling-mode slowdown.

The claim to be tested is specific: sampling mode is slow because the drafter's
per-node distributions are materialised as an (N+1) x vocab CPU tensor to
satisfy the CPU-RNG reproducibility contract, whereas greedy mode never
materialises them at all. If that is right, the cost must appear in the DRAFT
phase and scale with the tree budget and vocabulary -- not in verification, not
in the target forward.

Reports the phase breakdown side by side and the implied transfer volume, so
the go/no-go decision rests on where the time actually goes rather than on the
plausibility of the story.

    python scripts/e8_analyze.py --root results/e8 --out docs/tables/e8.md
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PHASES = [("prefill", "prefill"), ("draft", "draft"),
          ("tree_forward", "target tree forward"), ("topology", "topology"),
          ("mask", "mask"), ("verify", "verify"), ("commit", "kv/commit")]


def cell(root: Path, name: str):
    f = root / name / "benchmark.csv"
    if not f.exists():
        return None
    rows = list(csv.DictReader(f.open()))
    if not rows:
        return None
    r = rows[0]
    out = {"ms_per_token": float(r["spec_ms_per_token"]),
           "ar_ms_per_token": float(r["ar_ms_per_token"]),
           "speedup": float(r["speedup"]),
           "accept": float(r["mean_accept_len"])}
    for key, _ in PHASES:
        v = r.get(f"t_{key}_ms_per_step")
        out[key] = float(v) if v not in (None, "") else None
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/e8")
    ap.add_argument("--out", default="docs/tables/e8-sampling.md")
    ap.add_argument("--vocab", type=int, default=128256)
    ap.add_argument("--nodes", type=int, default=256)
    a = ap.parse_args()

    root = ROOT / a.root
    g = cell(root, "greedy-mtbench")
    t = cell(root, "temp1-mtbench")
    if not g or not t:
        print(f"missing E8 cells under {a.root} "
              f"(greedy={'ok' if g else 'absent'}, temp1={'ok' if t else 'absent'})")
        return 1

    lines = ["# E8 phase A --- where the sampling-mode slowdown lives", "",
             "Generated by `scripts/e8_analyze.py`. Timers on, so absolute values are",
             "inflated; read the COMPARISON between modes, not the magnitudes.", "",
             "| Metric | greedy | temperature 1.0 | ratio |", "|---|---|---|---|"]

    def row(label, kg, kt, unit=""):
        vg, vt = g.get(kg), t.get(kt)
        if vg is None or vt is None:
            return
        ratio = (vt / vg) if vg else float("inf")
        lines.append(f"| {label} | {vg:.3f}{unit} | {vt:.3f}{unit} | **{ratio:.1f}x** |")

    row("total ms/token", "ms_per_token", "ms_per_token")
    row("AR baseline ms/token", "ar_ms_per_token", "ar_ms_per_token")
    row("speedup vs AR", "speedup", "speedup")
    row("acceptance", "accept", "accept")
    lines.append("")
    lines += ["### Per-phase (ms/step)", "",
              "| Phase | greedy | temperature 1.0 | ratio | share of the extra time |",
              "|---|---|---|---|---|"]

    deltas = {}
    for key, label in PHASES:
        if g.get(key) is None or t.get(key) is None:
            continue
        deltas[label] = t[key] - g[key]
    total_delta = sum(v for v in deltas.values() if v > 0) or 1.0
    for key, label in PHASES:
        if g.get(key) is None or t.get(key) is None:
            continue
        d = t[key] - g[key]
        share = (d / total_delta) if d > 0 else 0.0
        lines.append(f"| {label} | {g[key]:.3f} | {t[key]:.3f} | "
                     f"{t[key]/g[key] if g[key] else float('inf'):.1f}x | "
                     f"{share:.0%} |")

    dominant = max(deltas, key=deltas.get) if deltas else None
    bytes_per_step = (a.nodes + 1) * a.vocab * 4
    lines += ["", "### Implied transfer volume", "",
              f"Sampling materialises an (N+1) x vocab float32 tensor per decode step:",
              f"`({a.nodes}+1) x {a.vocab} x 4 B` = **{bytes_per_step/2**20:.0f} MiB "
              "per step**, moved device-to-host. Greedy transfers N+1 integers.", ""]
    if dominant:
        lines.append(
            f"**The extra time is concentrated in `{dominant}` "
            f"({deltas[dominant]:+.3f} ms/step, {deltas[dominant]/total_delta:.0%} of "
            "the increase).**"
            + ("  That is where distribution materialisation happens, so the "
               "hypothesis is supported and a device-side RNG is the right fix."
               if dominant == "draft" else
               "  That is NOT where distribution materialisation happens, so the "
               "CPU-transfer explanation does not survive and the cause must be "
               "re-diagnosed before any engineering."))
    lines += ["", "### Go/no-go", "",
              "Per the protocol, sampling may be claimed as a speed contribution only",
              "if an optimised path reaches a lower 95% speedup bound above 1.0 and",
              "passes the distribution tests. On the evidence here the honest route is",
              "a greedy-only paper with this measurement reported as a limitation and",
              "an engineering lesson.", ""]

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(json.dumps({"dominant_phase": dominant, "deltas_ms_per_step": deltas,
                      "greedy_speedup": g["speedup"], "temp1_speedup": t["speedup"],
                      "transfer_MiB_per_step": bytes_per_step / 2**20}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
