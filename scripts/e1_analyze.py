"""Analyse E1 output: agreement with Wilson intervals, and margin bucketing.

Answers the two questions the protocol asks of E1:

  1. Does the procedure preserve the target's decoding rule in exact
     arithmetic?  -- float32 agreement must be exactly 1.0; anything less
     blocks the correctness claim rather than being reported as a number.
  2. What practical difference does bfloat16 make, and is it concentrated at
     near-ties?  -- the same-prefix top-1/top-2 margins say whether the flips
     are numerical coin-tosses or something worse.

    python scripts/e1_analyze.py --root results/e1 --out docs/tables/e1-summary.md
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Absolute-margin buckets, kept for reference.
BUCKETS = [(0, 1e-4), (1e-4, 1e-3), (1e-3, 1e-2), (1e-2, 1e-1), (1e-1, float("inf"))]
BUCKET_LABELS = ["<=1e-4", "1e-4..1e-3", "1e-3..1e-2", "1e-2..1e-1", ">1e-1"]

# ULP buckets. This is the physically meaningful scale: an absolute margin of
# 0.125 sounds wide, but near a logit of 16-32 it is exactly ONE unit in the
# last place of bfloat16 -- two tokens the format cannot distinguish. Bucketing
# in absolute units mixes magnitudes and manufactures an unexplained tail.
ULP_BUCKETS = [(0, 1), (1, 2), (2, 4), (4, 16), (16, float("inf"))]
ULP_LABELS = ["<1 ULP", "1-2 ULP", "2-4 ULP", "4-16 ULP", ">16 ULP"]


def wilson(k: int, n: int, z: float = 1.96):
    """Wilson score interval - correct at proportions near 1.0, unlike normal."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - half) / d, (c + half) / d)


def read(p: Path):
    return list(csv.DictReader(p.open())) if p.exists() else []


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/e1")
    ap.add_argument("--out", default="docs/tables/e1-summary.md")
    a = ap.parse_args()
    root = ROOT / a.root

    # ---- Procedures A / C: free-running agreement --------------------------
    agg = defaultdict(lambda: {"matched": 0, "compared": 0, "exact": 0, "seqs": 0,
                               "first_div": []})
    for f in sorted(root.glob("*/procedure_A_*.csv")):
        cell = f.parent.name
        prec = f.stem.replace("procedure_A_", "")
        for r in read(f):
            k = (cell, prec)
            agg[k]["matched"] += int(r["positions_matched"])
            agg[k]["compared"] += int(r["positions_compared"])
            agg[k]["exact"] += int(r["sequence_exact_match"])
            agg[k]["seqs"] += 1
            if int(r["first_divergence"]) >= 0:
                agg[k]["first_div"].append(int(r["first_divergence"]))

    lines = ["# E1 --- numerical correctness and bf16 fidelity",
             "",
             "Auto-generated by `scripts/e1_analyze.py`. Do not hand-edit.",
             "",
             "## Free-running equivalence (procedures A and C)",
             "",
             "| Cell | Precision | Positions | Agreement | 95% CI (Wilson) | Seqs exact | Median first divergence |",
             "|---|---|---|---|---|---|---|"]
    fp32_bad = []
    by_prec = defaultdict(lambda: [0, 0])
    for (cell, prec), v in sorted(agg.items()):
        lo, hi = wilson(v["matched"], v["compared"])
        rate = v["matched"] / max(v["compared"], 1)
        fd = sorted(v["first_div"])
        med = fd[len(fd) // 2] if fd else "--"
        lines.append(f"| {cell} | {prec} | {v['compared']} | {rate:.4f} | "
                     f"[{lo:.4f}, {hi:.4f}] | {v['exact']}/{v['seqs']} | {med} |")
        by_prec[prec][0] += v["matched"]
        by_prec[prec][1] += v["compared"]
        if prec == "float32" and rate < 1.0:
            fp32_bad.append(cell)

    lines += ["", "### Pooled by precision", "",
              "| Precision | Positions compared | Agreement | 95% CI |", "|---|---|---|---|"]
    for prec, (m, c) in sorted(by_prec.items()):
        lo, hi = wilson(m, c)
        lines.append(f"| {prec} | {c} | {m/max(c,1):.4f} | [{lo:.4f}, {hi:.4f}] |")

    if fp32_bad:
        lines += ["", f"> **FLOAT32 DIVERGENCE in {len(fp32_bad)} cell(s): "
                      f"{', '.join(fp32_bad)}.** The exact-arithmetic correctness "
                      "claim is blocked until this is explained.", ""]
    elif by_prec.get("float32", [0, 0])[1] > 0:
        m, c = by_prec["float32"]
        lines += ["", f"> **float32 agreement is exact: {m}/{c} positions.** The "
                      "decoding rule is preserved in exact arithmetic, so any bf16 "
                      "difference is arithmetic rather than a verification defect.", ""]

    # ---- Procedure B: margins at agreeing vs disagreeing positions ---------
    rows = []
    for f in sorted(root.glob("*/procedure_B_*.csv")):
        prec = f.stem.replace("procedure_B_", "")
        for r in read(f):
            rows.append((prec, int(r["argmax_agrees"]), float(r["top1_top2_margin"]),
                         float(r["max_abs_logit_diff"]),
                         float(r.get("margin_in_ulps") or "nan")))
    if rows:
        lines += ["## Same-prefix comparison (procedure B)", "",
                  "Sequential vs batched target forward on an *identical* prefix, so a",
                  "disagreement is numerical rather than the two runs having drifted apart.",
                  "",
                  "| Precision | Positions | Argmax agree | Median margin (agree) | Median margin (disagree) | Median max abs logit diff |",
                  "|---|---|---|---|---|---|"]
        for prec in sorted({r[0] for r in rows}):
            sub = [r for r in rows if r[0] == prec]
            ok = [r[2] for r in sub if r[1] == 1]
            no = [r[2] for r in sub if r[1] == 0]
            dif = sorted(r[3] for r in sub)
            med = lambda xs: f"{sorted(xs)[len(xs)//2]:.4g}" if xs else "--"
            lines.append(f"| {prec} | {len(sub)} | {len(ok)}/{len(sub)} "
                         f"({len(ok)/len(sub):.4f}) | {med(ok)} | {med(no)} | "
                         f"{med(dif)} |")

        lines += ["", "### Disagreements bucketed by top-1/top-2 margin", "",
                  "| Precision | " + " | ".join(BUCKET_LABELS) + " |",
                  "|---" * (len(BUCKET_LABELS) + 1) + "|"]
        for prec in sorted({r[0] for r in rows}):
            sub = [r for r in rows if r[0] == prec and r[1] == 0]
            counts = []
            for lo_b, hi_b in BUCKETS:
                counts.append(sum(1 for r in sub if lo_b <= r[2] < hi_b))
            tot = max(len(sub), 1)
            cells_ = [f"{c} ({c/tot:.0%})" for c in counts]
            lines.append(f"| {prec} | " + " | ".join(cells_) + " |")
        # ULP view, when procedure B recorded it.
        have_ulp = any(r[4] == r[4] for r in rows)     # NaN-safe
        if have_ulp:
            lines += ["", "### Disagreements bucketed by margin in ULPs of the "
                          "execution dtype", "",
                      "| Precision | " + " | ".join(ULP_LABELS) + " |",
                      "|---" * (len(ULP_LABELS) + 1) + "|"]
            for prec in sorted({r[0] for r in rows}):
                sub = [r for r in rows if r[0] == prec and r[1] == 0
                       and r[4] == r[4]]
                counts = [sum(1 for r in sub if lo_b <= r[4] < hi_b)
                          for lo_b, hi_b in ULP_BUCKETS]
                tot = max(len(sub), 1)
                lines.append(f"| {prec} | "
                             + " | ".join(f"{c} ({c/tot:.0%})" for c in counts) + " |")
            lines += ["", "This is the scale that matters. A margin measured in ULPs "
                          "says whether the two candidates are distinguishable AT THE "
                          "PRECISION BEING USED; an absolute threshold mixes logit "
                          "magnitudes and invents an unexplained tail.", ""]
        lines += ["", "A disagreement distribution concentrated in the smallest margin "
                      "buckets is the signature of near-tie rounding, not of a "
                      "verification defect.", ""]

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    summary = {"cells": len(agg),
               "float32_divergent_cells": fp32_bad,
               "pooled": {p: {"matched": m, "compared": c} for p, (m, c) in by_prec.items()},
               "procedure_b_positions": len(rows)}
    print(json.dumps(summary, indent=2))
    return 2 if fp32_bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
