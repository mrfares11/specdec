"""E3 --- drafter x tree interaction and transfer, from E2's raw latency.

No new GPU work: this reads the per-prompt rows E2 wrote and answers three
questions with intervals rather than point estimates.

  G(d) = L(d, static) - L(d, dynamic)      dynamic gain for drafter d, ms/token
  I    = G(scaled) - G(v1.0)               drafter x tree interaction
  T    = G(official EAGLE)                 transfer to a drafter we did not train

Positive G means dynamic is faster. Positive I means dynamic reallocation
benefits MORE from a better drafter. Positive T means the tree mechanism
transfers to an independently trained drafter.

Two design choices worth stating, because they decide whether the intervals
mean anything:

  * Everything is PAIRED BY PROMPT. The same prompt under static and dynamic is
    one observation of the difference, so prompt difficulty -- which varies far
    more than the effect -- cancels instead of inflating the variance.
  * The bootstrap resamples PROMPTS and REPEATS, not individual token
    measurements. Tokens within a prompt are not independent, and treating them
    as such would produce intervals that are far too narrow.

    python scripts/e3_interaction.py --root results/e2 --out docs/tables/e3.md
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
N_BOOT = 10000
BOOT_SEED = 20260904


def load(root: Path):
    """rows[(bench, K, drafter, tree)][prompt_id] = [ms_per_token, ...]"""
    rows = defaultdict(lambda: defaultdict(list))
    meta = defaultdict(set)
    for f in sorted(root.glob("*/raw_prompt_results.csv")):
        cell = f.parent.name           # e.g. scaled-dyn-humaneval-k4-s1-r2
        parts = cell.split("-")
        if len(parts) < 6:
            continue
        drafter, tree = parts[0], parts[1]
        for r in csv.DictReader(f.open()):
            try:
                bench = r["benchmark"]
                K = int(float(r["K"]))
                pid = int(r["prompt_id"])
                ms = float(r["ms_per_token"])
            except (KeyError, ValueError):
                continue
            rows[(bench, K, drafter, tree)][pid].append(ms)
            meta["benchmarks"].add(bench)
            meta["Ks"].add(K)
            meta["drafters"].add(drafter)
    return rows, meta


def paired_gain(rows, bench, K, drafter, pids):
    """Mean over prompts of (static - dynamic) for one drafter."""
    st = rows.get((bench, K, drafter, "static"), {})
    dy = rows.get((bench, K, drafter, "dyn"), {})
    diffs = []
    for p in pids:
        if p in st and p in dy:
            diffs.append(statistics.mean(st[p]) - statistics.mean(dy[p]))
    return statistics.mean(diffs) if diffs else None


def common_prompts(rows, bench, K, drafters):
    sets = []
    for d in drafters:
        for t in ("static", "dyn"):
            s = set(rows.get((bench, K, d, t), {}))
            if s:
                sets.append(s)
    return sorted(set.intersection(*sets)) if sets else []


def boot_ci(fn, pids, n=N_BOOT, seed=BOOT_SEED):
    """Percentile bootstrap resampling PROMPTS (the independent unit)."""
    rng = random.Random(seed)
    vals = []
    for _ in range(n):
        sample = [pids[rng.randrange(len(pids))] for _ in range(len(pids))]
        v = fn(sample)
        if v is not None:
            vals.append(v)
    if not vals:
        return None, None
    vals.sort()
    return vals[int(0.025 * len(vals))], vals[int(0.975 * len(vals))]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/e2")
    ap.add_argument("--out", default="docs/tables/e3-interaction.md")
    ap.add_argument("--boot", type=int, default=N_BOOT)
    a = ap.parse_args()

    rows, meta = load(ROOT / a.root)
    if not rows:
        print(f"no E2 raw rows under {a.root}")
        return 1

    benches = sorted(meta["benchmarks"])
    Ks = sorted(meta["Ks"])
    have = meta["drafters"]

    lines = ["# E3 --- drafter x tree interaction and transfer", "",
             "Generated by `scripts/e3_interaction.py` from E2's per-prompt latency.",
             "No new GPU work. All quantities are paired by prompt; intervals are",
             f"percentile bootstraps over prompts ({a.boot} resamples, seed {BOOT_SEED}).",
             "",
             "`G` = static minus dynamic ms/token (positive: dynamic is faster).",
             "`I` = G(scaled) - G(v1.0)  ---  does a better drafter get more from the tree?",
             "`T` = G(EAGLE)  ---  does the tree transfer to a drafter we did not train?",
             "",
             "| Benchmark | K | G(v1.0) | G(scaled) | I = interaction [95% CI] | T = G(EAGLE) [95% CI] |",
             "|---|---|---|---|---|---|"]

    summary = {}
    for bench in benches:
        for K in Ks:
            drafters = [d for d in ("base", "scaled", "eagle") if d in have]
            pids = common_prompts(rows, bench, K, drafters)
            if len(pids) < 5:
                continue
            g_base = paired_gain(rows, bench, K, "base", pids)
            g_scaled = paired_gain(rows, bench, K, "scaled", pids)
            g_eagle = paired_gain(rows, bench, K, "eagle", pids)
            if g_base is None or g_scaled is None:
                continue

            def inter(sample):
                a_ = paired_gain(rows, bench, K, "scaled", sample)
                b_ = paired_gain(rows, bench, K, "base", sample)
                return None if a_ is None or b_ is None else a_ - b_

            def transfer(sample):
                return paired_gain(rows, bench, K, "eagle", sample)

            i_lo, i_hi = boot_ci(inter, pids, a.boot)
            t_lo, t_hi = (boot_ci(transfer, pids, a.boot) if g_eagle is not None
                          else (None, None))
            I = g_scaled - g_base
            fmt = lambda x: "--" if x is None else f"{x:+.3f}"
            ci = lambda lo, hi: "--" if lo is None else f"[{lo:+.3f}, {hi:+.3f}]"
            lines.append(
                f"| {bench} | {K} | {fmt(g_base)} | {fmt(g_scaled)} | "
                f"{fmt(I)} {ci(i_lo, i_hi)} | {fmt(g_eagle)} {ci(t_lo, t_hi)} |")
            summary[f"{bench}-k{K}"] = {
                "n_prompts": len(pids), "G_base": g_base, "G_scaled": g_scaled,
                "I": I, "I_ci": [i_lo, i_hi], "T": g_eagle, "T_ci": [t_lo, t_hi],
                "I_excludes_zero": bool(i_lo is not None and i_lo > 0),
                "T_excludes_zero": bool(t_lo is not None and t_lo > 0)}

    # Wording is dictated by the intervals, not chosen after seeing them.
    n_i = sum(1 for v in summary.values() if v["I_excludes_zero"])
    n_t = sum(1 for v in summary.values() if v["T_excludes_zero"])
    lines += ["", "## Permitted claims", ""]
    if summary:
        lines.append(
            f"- Interaction is positive with a 95% interval excluding zero in "
            f"**{n_i} of {len(summary)}** cells."
            + ("  A statistically supported positive interaction may be claimed "
               "for those cells only."
               if n_i else
               "  No cell supports a *statistically significant* interaction; the "
               "correct wording is \"directionally positive in all evaluated "
               "cells\" with the intervals reported."))
        lines.append(
            f"- Transfer to the official EAGLE drafter is positive with a 95% "
            f"interval excluding zero in **{n_t} of {len(summary)}** cells."
            + ("  Transfer may be claimed, scoped to cross-drafter transfer for "
               "the same verifier."
               if n_t else "  Transfer is not statistically supported here."))
    lines += ["", "Percentages must be regenerated from unrounded latency, never "
                  "from rounded speedups.", ""]

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(json.dumps(summary, indent=2, default=float))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
