"""E2 --- headline timing table and the protocol's predeclared comparisons.

Builds Gate B's deliverable from E2's per-prompt rows: raw ms/token beside every
speedup, confidence intervals from a paired bootstrap, and per-session results
rather than only the pooled mean.

The comparisons below are the ones the protocol names in advance. They are
evaluated as stated, and the wording each supports is derived from its interval
rather than chosen after looking:

    scaled+dyn K=4  vs  AR
    scaled+dyn K=4  vs  scaled+static K=4
    scaled+dyn K=4  vs  base+dyn K=4
    eagle+dyn  K=4  vs  eagle+static K=4
    K=4 vs K=8 within every drafter x tree combination

    python scripts/e2_analyze.py --root results/e2 --out docs/tables/e2.md
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
N_BOOT = 10000
BOOT_SEED = 20260904


def load(root: Path):
    """cells[(bench,K,drafter,tree)][session][prompt_id] = {"ms":[], "ar":[], "acc":[]}"""
    cells = defaultdict(lambda: defaultdict(lambda: defaultdict(
        lambda: {"ms": [], "ar": [], "acc": []})))
    for f in sorted(root.glob("*/raw_prompt_results.csv")):
        parts = f.parent.name.split("-")
        if len(parts) < 6:
            continue
        drafter, tree = parts[0], parts[1]
        session = parts[-2]
        for r in csv.DictReader(f.open()):
            try:
                key = (r["benchmark"], int(float(r["K"])), drafter, tree)
                pid = int(r["prompt_id"])
                d = cells[key][session][pid]
                d["ms"].append(float(r["ms_per_token"]))
                d["ar"].append(float(r["ar_ms_per_token"]))
                d["acc"].append(float(r["mean_accept_len"]))
            except (KeyError, ValueError):
                continue
    return cells


def flat(cell):
    """Per-prompt means pooled across sessions -> {pid: (ms, ar, acc)}"""
    out = {}
    for sess, prompts in cell.items():
        for pid, d in prompts.items():
            if d["ms"]:
                out.setdefault(pid, {"ms": [], "ar": [], "acc": []})
                out[pid]["ms"] += d["ms"]
                out[pid]["ar"] += d["ar"]
                out[pid]["acc"] += d["acc"]
    return {p: (statistics.mean(v["ms"]), statistics.mean(v["ar"]),
                statistics.mean(v["acc"])) for p, v in out.items()}


def boot(fn, pids, n, seed=BOOT_SEED):
    rng = random.Random(seed)
    vals = []
    for _ in range(n):
        s = [pids[rng.randrange(len(pids))] for _ in range(len(pids))]
        v = fn(s)
        if v is not None:
            vals.append(v)
    if not vals:
        return None, None
    vals.sort()
    return vals[int(0.025 * len(vals))], vals[int(0.975 * len(vals))]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/e2")
    ap.add_argument("--out", default="docs/tables/e2-headline.md")
    ap.add_argument("--boot", type=int, default=N_BOOT)
    a = ap.parse_args()

    cells = load(ROOT / a.root)
    if not cells:
        print(f"no E2 rows under {a.root}")
        return 1

    lines = ["# E2 --- headline timing (Gate B)", "",
             "Generated by `scripts/e2_analyze.py`. Raw ms/token appears beside every",
             "speedup, as the protocol requires. Speedup is computed per prompt against",
             "the autoregressive measurement from the SAME run, then bootstrapped over",
             f"prompts ({a.boot} resamples, seed {BOOT_SEED}).", "",
             "| Benchmark | Drafter | Tree | K | ms/token | speedup [95% CI] | accept | n runs | sessions |",
             "|---|---|---|---|---|---|---|---|---|"]

    table = {}
    for key in sorted(cells):
        bench, K, drafter, tree = key
        per = flat(cells[key])
        if len(per) < 5:
            continue
        pids = sorted(per)
        ms = statistics.mean(per[p][0] for p in pids)
        acc = statistics.mean(per[p][2] for p in pids)
        spd = statistics.mean(per[p][1] / per[p][0] for p in pids)
        lo, hi = boot(lambda s: statistics.mean(per[p][1] / per[p][0] for p in s),
                      pids, a.boot)
        n_runs = sum(len(v["ms"]) for sess in cells[key].values() for v in sess.values())
        sessions = sorted(cells[key])
        lines.append(f"| {bench} | {drafter} | {tree} | {K} | {ms:.2f} | "
                     f"{spd:.3f} [{lo:.3f}, {hi:.3f}] | {acc:.3f} | "
                     f"{n_runs // max(len(pids),1)} | {','.join(sessions)} |")
        table[key] = {"ms": ms, "speedup": spd, "ci": [lo, hi], "accept": acc,
                      "per_prompt": per, "sessions": sessions}

    # ---- predeclared comparisons ------------------------------------------
    lines += ["", "## Predeclared comparisons", "",
              "| Comparison | Benchmark | Delta ms/token [95% CI] | Verdict |",
              "|---|---|---|---|"]

    def paired_delta(k_a, k_b, label, bench):
        if k_a not in table or k_b not in table:
            return
        A, B = table[k_a]["per_prompt"], table[k_b]["per_prompt"]
        pids = sorted(set(A) & set(B))
        if len(pids) < 5:
            return
        d = lambda s: statistics.mean(B[p][0] - A[p][0] for p in s)  # B minus A
        point = d(pids)
        lo, hi = boot(d, pids, a.boot)
        better = "A faster" if point > 0 else "B faster"
        sig = "excludes zero" if (lo is not None and (lo > 0 or hi < 0)) else "includes zero"
        lines.append(f"| {label} | {bench} | {point:+.3f} [{lo:+.3f}, {hi:+.3f}] | "
                     f"{better}, {sig} |")

    for bench in sorted({k[0] for k in table}):
        paired_delta((bench, 4, "scaled", "dyn"), (bench, 4, "scaled", "static"),
                     "scaled+dyn vs scaled+static (K=4)", bench)
        paired_delta((bench, 4, "scaled", "dyn"), (bench, 4, "base", "dyn"),
                     "scaled+dyn vs base+dyn (K=4)", bench)
        paired_delta((bench, 4, "eagle", "dyn"), (bench, 4, "eagle", "static"),
                     "EAGLE dyn vs EAGLE static (K=4)", bench)
        for drafter in ("base", "scaled", "eagle"):
            for tree in ("static", "dyn"):
                paired_delta((bench, 4, drafter, tree), (bench, 8, drafter, tree),
                             f"K=4 vs K=8 ({drafter}+{tree})", bench)

    # ---- decision rules ----------------------------------------------------
    lines += ["", "## Decision rules", ""]
    main_ok, main_cells = [], []
    for key, v in table.items():
        if key[2] == "scaled" and key[3] == "dyn" and key[1] == 4:
            main_cells.append((key[0], v["ci"][0]))
            main_ok.append(v["ci"][0] is not None and v["ci"][0] > 1.0)
    if main_cells:
        lines.append(
            "- **Main speedup claim** requires the lower 95% bound above 1.0 for "
            "scaled+dynamic at K=4: "
            + "; ".join(f"{b} lower bound {lo:.3f}" for b, lo in main_cells)
            + f".  {'SUPPORTED' if all(main_ok) else 'NOT SUPPORTED in every cell'}.")
    k_rows = [(k, v) for k, v in table.items()]
    faster4 = 0
    total4 = 0
    for bench in sorted({k[0] for k in table}):
        for drafter in ("base", "scaled", "eagle"):
            for tree in ("static", "dyn"):
                a4, a8 = (bench, 4, drafter, tree), (bench, 8, drafter, tree)
                if a4 in table and a8 in table:
                    total4 += 1
                    faster4 += table[a4]["ms"] < table[a8]["ms"]
    if total4:
        lines.append(
            f"- **\"K=4 is faster\"** holds in **{faster4} of {total4}** "
            "drafter x tree x benchmark combinations."
            + ("  The unqualified claim is supported."
               if faster4 == total4 else
               "  The claim must be narrowed to the cells where it holds."))
    lines.append("- Percentages must be regenerated from unrounded latency, never "
                 "from rounded speedups.")

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(json.dumps({"cells": len(table),
                      "sessions": sorted({s for v in table.values()
                                          for s in v["sessions"]}),
                      "k4_faster": f"{faster4}/{total4}"}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
