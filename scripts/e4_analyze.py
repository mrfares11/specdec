"""E4 --- host thread sensitivity.

Reads the thread-cap sweep and answers the three things the protocol asks:

  1. How does latency move with the host thread cap, and does the dynamic tree
     behave differently from static decode and from the AR baseline?
  2. Does the uncapped configuration actually reverse the conclusion?
  3. Are acceptance and generated output UNCHANGED across caps?  This is the
     control that makes the whole experiment interpretable -- if acceptance
     moved with the thread count, the caps would be changing what is computed
     rather than how fast it is computed, and no latency comparison would mean
     anything.

    python scripts/e4_analyze.py --root results/e4 --out docs/tables/e4.md
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# sweep-<bench>-<tree>-k<K>-t<cap>
NAME = re.compile(r"^sweep-(?P<bench>[a-z0-9]+)-(?P<tree>static|dyn)-k(?P<K>\d+)-t(?P<cap>\d+)$")


def load(root: Path):
    cells = {}
    for d in sorted(root.glob("sweep-*")):
        m = NAME.match(d.name)
        f = d / "benchmark.csv"
        if not m or not f.exists():
            continue
        rows = list(csv.DictReader(f.open()))
        if not rows:
            continue
        r = rows[0]
        raw = d / "raw_prompt_results.csv"
        per_prompt = list(csv.DictReader(raw.open())) if raw.exists() else []
        cells[(m["bench"], m["tree"], int(m["K"]), int(m["cap"]))] = {
            "ms": float(r["spec_ms_per_token"]),
            "ar_ms": float(r["ar_ms_per_token"]),
            "speedup": float(r["speedup"]),
            "accept": float(r["mean_accept_len"]),
            "n_prompts": len(per_prompt),
            "hashes": sorted({p.get("output_token_hash", "") for p in per_prompt}),
        }
    return cells


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/e4")
    ap.add_argument("--out", default="docs/tables/e4-host-sensitivity.md")
    a = ap.parse_args()
    cells = load(ROOT / a.root)
    if not cells:
        print(f"no E4 sweep cells under {a.root}")
        return 1

    caps = sorted({k[3] for k in cells})
    benches = sorted({k[0] for k in cells})
    configs = sorted({(k[1], k[2]) for k in cells})

    lines = ["# E4 --- host thread sensitivity", "",
             "Generated by `scripts/e4_analyze.py`. Development prompts only: the",
             "cap must never be selected on the reported test set.", "",
             "## Latency (ms/token) vs host thread cap", "",
             "| Benchmark | Config | " + " | ".join(f"t={c}" for c in caps)
             + " | best cap | worst/best |",
             "|---" * (len(caps) + 4) + "|"]

    findings = {}
    for b in benches:
        for tree, K in configs:
            row = [cells.get((b, tree, K, c)) for c in caps]
            if not any(row):
                continue
            vals = [(c, r["ms"]) for c, r in zip(caps, row) if r]
            best = min(vals, key=lambda x: x[1])
            worst = max(vals, key=lambda x: x[1])
            cellstr = [f"{r['ms']:.2f}" if r else "--" for r in row]
            lines.append(f"| {b} | {tree} K={K} | " + " | ".join(cellstr)
                         + f" | **t={best[0]}** | {worst[1]/best[1]:.2f}x |")
            findings[f"{b}-{tree}-k{K}"] = {
                "best_cap": best[0], "best_ms": best[1],
                "worst_cap": worst[0], "worst_ms": worst[1],
                "worst_over_best": worst[1] / best[1],
                "by_cap": {str(c): (r["ms"] if r else None) for c, r in zip(caps, row)},
            }

    # ---- speedup, i.e. does the conclusion actually flip? -----------------
    lines += ["", "## Speedup vs AR, by thread cap", "",
              "| Benchmark | Config | " + " | ".join(f"t={c}" for c in caps) + " |",
              "|---" * (len(caps) + 2) + "|"]
    flips = []
    for b in benches:
        for tree, K in configs:
            row = [cells.get((b, tree, K, c)) for c in caps]
            if not any(row):
                continue
            sp = [r["speedup"] if r else None for r in row]
            lines.append(f"| {b} | {tree} K={K} | "
                         + " | ".join(f"{s:.2f}x" if s else "--" for s in sp) + " |")
            got = [s for s in sp if s]
            if got and min(got) < 1.0 <= max(got):
                flips.append(f"{b} {tree} K={K}")
    if flips:
        lines += ["", f"> **The conclusion reverses with the thread cap in "
                      f"{len(flips)} configuration(s):** {', '.join(flips)}. "
                      "The same code and GPU cross the 1.0x line purely on host "
                      "thread configuration.", ""]

    # ---- the control: acceptance must not move with the cap ---------------
    lines += ["## Control: acceptance across thread caps", "",
              "Thread count must change only how fast the work runs, never what is",
              "computed. Acceptance drifting with the cap would invalidate every",
              "latency comparison above.", "",
              "| Benchmark | Config | distinct acceptance values | verdict |",
              "|---|---|---|---|"]
    control_ok = True
    for b in benches:
        for tree, K in configs:
            vals = [cells[(b, tree, K, c)]["accept"] for c in caps
                    if (b, tree, K, c) in cells]
            if not vals:
                continue
            uniq = sorted({round(v, 6) for v in vals})
            ok = len(uniq) == 1
            control_ok &= ok
            lines.append(f"| {b} | {tree} K={K} | {len(uniq)} "
                         f"({', '.join(f'{u:.4f}' for u in uniq[:3])}"
                         f"{'...' if len(uniq) > 3 else ''}) | "
                         + ("identical" if ok else "**MOVED**") + " |")
    lines += ["", ("> Acceptance is identical at every thread cap, so the sweep "
                   "isolates execution speed alone."
                   if control_ok else
                   "> **WARNING: acceptance moved with the thread cap.** The caps are "
                   "changing what is computed, not just how fast; latency "
                   "comparisons above are not interpretable until this is "
                   "explained."), ""]

    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    print(json.dumps({"caps": caps, "acceptance_control_passed": control_ok,
                      "conclusion_flips": flips, "cells": findings},
                     indent=2, default=float)[:2000])
    return 0 if control_ok else 2


if __name__ == "__main__":
    raise SystemExit(main())
